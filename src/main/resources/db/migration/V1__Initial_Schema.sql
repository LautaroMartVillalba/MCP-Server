create table entity_person (
    age integer not null check (age>=18), 
    number_of_reservations integer not null, 
    address_id bigint unique, 
    id bigint generated by default as identity, 
    name varchar(52) not null, 
    cell_phone_number varchar(255) not null unique, 
    dni varchar(255) not null unique, 
    email varchar(255) not null unique, 
    primary key (id)
);

create table entity_reservation (
    end_at date not null, 
    start_at date not null, 
    total_price numeric(38,2) not null, 
    id bigint generated by default as identity, 
    number_of_nights bigint not null check (number_of_nights>=1), 
    number_of_people bigint not null check ((number_of_people<=4) and (number_of_people>=1)), 
    person_id bigint not null, 
    room_id bigint not null, 
    primary key (id)
);

create table entity_room (
    floor integer not null check (floor>=1), 
    number_of_beds integer not null check ((number_of_beds<=4) and (number_of_beds>=1)), 
    people_capacity integer not null check ((people_capacity<=4) and (people_capacity>=1)), 
    price_per_night numeric(38,2) not null, 
    hotel_id bigint not null, 
    id bigint generated by default as identity, 
    times_booked bigint not null, 
    bed_type varchar(255) not null check (bed_type in (
        'SINGLE',
        'DOUBLE',
        'QUEEN',
        'KING',
        'TWIN')
    ), 
    room_type varchar(255) not null check (room_type in (
        'STANDARD',
        'DELUXE',
        'SUITE',
        'EXECUTIVE',
        'PRESIDENTIAL')
    ), 
    state varchar(255) not null check (state in (
        'OCCUPIED',
        'UNOCCUPIED',
        'BEING_CLEANED',
        'CLEANED',
        'FREE',
        'RESERVED')
    ), 
    primary key (id)
);

create table entity_room_booking_period (
    end_at date not null, 
    start_at date not null, 
    id bigint generated by default as identity, 
    reservation_id bigint not null unique, 
    room_id bigint not null, 
    status varchar(255) not null check (status in (
        'RESERVED',
        'CANCELLED',
        'COMPLETED',
        'BLOCKED')
    ), 
    primary key (id)
);

create table entity_states (
    code varchar(255) not null, 
    country_code varchar(255), 
    subdivision_name varchar(255), 
    primary key (code)
