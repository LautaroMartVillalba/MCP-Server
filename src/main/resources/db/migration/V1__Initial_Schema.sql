create table entity_address (
    entity_hotel_id bigint unique,
    id bigint generated by default as identity, 
    address_type varchar(31) not null, 
    door_number varchar(255), 
    floor varchar(255), 
    number varchar(255), 
    state_code varchar(255), 
    street varchar(255), 
    primary key (id)
);

create table entity_attraction (
    close_at time(6) not null, 
    open_at time(6) not null, 
    people_capacity integer not null, 
    id bigint generated by default as identity, 
    name varchar(20) not null, 
    description varchar(500) not null, 
    primary key (id)
);

create table entity_benefit (
    close_at time(6) not null, 
    open_at time(6) not null, 
    id bigint generated by default as identity, 
    name varchar(20) not null, 
    description varchar(500) not null, 
    primary key (id)
);

create table entity_hotel (
    free_rooms integer not null, 
    reserved_rooms integer not null, 
    stars float(53) not null, 
    total_rooms integer not null check (total_rooms>=2), 
    id bigint generated by default as identity, 
    contact_phone varchar(24) not null unique, 
    name varchar(90) not null, 
    primary key (id)
);

